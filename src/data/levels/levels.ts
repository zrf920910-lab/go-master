import type { LevelDef, Chapter, PositionSpec } from '../../app/types';
import { pos } from '../../learning/Exercises/pos';

/**
 * The 30-level challenge system.
 *
 * Every stage is a real board position solved with a real move. The `answer`
 * is the canonical solution, and `tests/content.test.ts` replays it to prove
 * that it is legal and satisfies the stage's semantic check — so a level can
 * never ship unsolvable.
 *
 * Stage ids are assigned automatically (`s1`, `s2`, …).
 */

interface StageInput {
  title: string;
  tag: string;
  stones: readonly string[];
  turn: 1 | 2;
  prompt: string;
  detail?: string;
  check: LevelDef['stages'][number]['check'];
  answer: string;
  success: string;
  wrong: string;
  hint: string;
  size?: number;
  interaction?: 'play' | 'tap';
  maxMoves?: number;
  twoStarMoves?: number;
  xp?: number;
  ko?: string;
}

function mkStage(s: StageInput, i: number) {
  const position: PositionSpec = pos(s.size ?? 9, [...s.stones], s.turn);
  if (s.ko) position.ko = s.ko;
  return {
    id: `s${i + 1}`,
    title: s.title,
    tag: s.tag,
    interaction: s.interaction,
    position,
    prompt: s.prompt,
    detail: s.detail,
    check: s.check,
    answer: s.answer,
    success: s.success,
    wrong: s.wrong,
    hint: s.hint,
    maxMoves: s.maxMoves ?? 1,
    twoStarMoves: s.twoStarMoves ?? 1,
    xp: s.xp ?? 20,
  };
}

function mkLevel(
  id: string,
  index: number,
  chapter: number,
  title: string,
  blurb: string,
  goal: string,
  icon: string,
  stages: StageInput[],
): LevelDef {
  return { id, index, chapter, title, blurb, goal, icon, stages: stages.map(mkStage) };
}

